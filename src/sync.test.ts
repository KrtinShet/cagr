const own = (event: string, agent = "claude") =>
	`cagr hook ${event} --agent ${agent}`;

describe("mergeHooks", () => {
	test("keeps the user's hooks, replaces cagr's, and is stable", () => {
		const user = { type: "command" as const, command: "echo mine", timeout: 5 };
		const current = {
			permissions: { allow: ["Bash(ls)"] },
			hooks: {
				PreToolUse: [
					{
						matcher: "Bash",
						hooks: [
							user,
							{
								type: "command" as const,
								command: "old/cagr hook command.before --agent claude",
								timeout: 1,
							},
						],
					},
				],
				Stop: [
					{
						hooks: [
							{
								type: "command" as const,
								command: own("turn.end"),
								timeout: 1,
							},
						],
					},
				],
			},
		};
		const merged = mergeHooks(current, config(), "claude");
		expect(merged.permissions).toEqual({ allow: ["Bash(ls)"] });
		expect(merged.hooks?.PreToolUse).toEqual([
			{ matcher: "Bash", hooks: [user] },
			{
				matcher: "Bash",
				hooks: [
					{ type: "command", command: own("command.before"), timeout: 10 },
				],
			},
			{
				matcher: "Edit|Write|MultiEdit|NotebookEdit",
				hooks: [
					{ type: "command", command: own("file.before_edit"), timeout: 10 },
				],
			},
		]);
		expect(merged.hooks?.Stop).toEqual([
			{ hooks: [{ type: "command", command: own("turn.end"), timeout: 300 }] },
		]);
		expect(mergeHooks(merged, config(), "claude")).toEqual(merged);
	});

	test("Codex gets regex matchers that include apply_patch", () => {
		const merged = mergeHooks({}, config(), "codex");
		expect(merged.hooks?.PostToolUse?.[0]?.matcher).toBe(
			"^(apply_patch|Edit|Write)$",
		);
		expect(merged.hooks?.SessionStart?.[0]).toEqual({
			hooks: [
				{
					type: "command",
					command: own("session.start", "codex"),
					timeout: 10,
				},
			],
		});
	});
});

test("{root} in the command becomes each agent's repo root", () => {
	const repo = config({ agents: { command: "{root}/bin/cagr" } });
	expect(hookCommand(repo, "claude", "turn.end")).toBe(
		'"$CLAUDE_PROJECT_DIR"/bin/cagr hook turn.end --agent claude',
	);
	expect(hookCommand(repo, "codex", "turn.end")).toBe(
		'"$(git rev-parse --show-toplevel)"/bin/cagr hook turn.end --agent codex',
	);
});

test("git hook scripts are marked generated and skip when cagr is missing", () => {
	const script = gitHookScript(config(), "pre-push");
	expect(script.split("\n").slice(0, 2)).toEqual([
		"#!/bin/sh",
		expect.stringContaining("Generated by `cagr sync`"),
	]);
	expect(script).toContain("command -v cagr");
	expect(script).toEndWith('exec cagr git pre-push "$@"\n');
	expect(
		gitHookScript(config({ agents: { command: "{root}/gw" } }), "commit-msg"),
	).not.toContain("command -v");
});

describe("sync", () => {
	async function repo() {
		const root = await mkdtemp(join(tmpdir(), "gw-sync-"));
		return resolveConfig({}, root, join(root, "cagr.toml"));
	}

	test("writes every file, then --check passes, then reports drift", async () => {
		const repoConfig = await repo();
		expect(sync(repoConfig).written).toEqual([
			".claude/settings.json",
			".codex/hooks.json",
			".githooks/commit-msg",
			".githooks/pre-push",
		]);
		expect(
			(await stat(join(repoConfig.root, ".githooks/pre-push"))).mode & 0o111,
		).toBeTruthy();
		expect(sync(repoConfig, { check: true }).drifted).toEqual([]);
		await writeFile(
			join(repoConfig.root, ".githooks/commit-msg"),
			"#!/bin/sh\n",
		);
		expect(sync(repoConfig, { check: true }).drifted).toEqual([
			".githooks/commit-msg",
		]);
	});

	test("JSON formatting alone is not drift", async () => {
		const repoConfig = await repo();
		sync(repoConfig);
		const file = join(repoConfig.root, ".claude/settings.json");
		await writeFile(
			file,
			JSON.stringify(JSON.parse(await readFile(file, "utf8"))),
		);
		expect(sync(repoConfig, { check: true }).drifted).toEqual([]);
	});

	test("a rewrite keeps the file's indent", async () => {
		const repoConfig = await repo();
		await mkdir(join(repoConfig.root, ".claude"));
		const file = join(repoConfig.root, ".claude/settings.json");
		await writeFile(file, '{\n\t"permissions": {}\n}\n');
		sync(repoConfig);
		expect(await readFile(file, "utf8")).toStartWith(
			'{\n\t"permissions": {},\n\t"hooks": {\n\t\t',
		);
		expect(indentOf('{\n    "a": 1\n}')).toBe(4);
		expect(indentOf(null)).toBe(2);
	});

	test("refuses to overwrite invalid JSON", async () => {
		const repoConfig = await repo();
		await mkdir(join(repoConfig.root, ".claude"));
		await writeFile(join(repoConfig.root, ".claude/settings.json"), "{ nope");
		expect(() => sync(repoConfig)).toThrow(
			".claude/settings.json is not valid JSON",
		);
	});

	test("turning [ci] github off deletes the workflow sync wrote, not one a person wrote", async () => {
		const root = await mkdtemp(join(tmpdir(), "gw-sync-"));
		const make = (github: boolean) =>
			resolveConfig({ agents: { enabled: [] }, ci: { github } }, root, "x");
		sync(make(true));
		const workflow = join(root, ".github/workflows/cagr.yml");
		expect(await readFile(workflow, "utf8")).toContain(
			"Generated by `cagr sync`",
		);
		expect(sync(make(false), { check: true }).drifted).toEqual([
			".github/workflows/cagr.yml",
		]);
		expect(sync(make(false)).removed).toEqual([
			{ file: ".github/workflows/cagr.yml", why: "[ci] github is off." },
		]);
		expect(await Bun.file(workflow).exists()).toBe(false);
		await writeFile(workflow, "name: mine\n");
		expect(sync(make(false)).removed).toEqual([]);
		expect(await readFile(workflow, "utf8")).toBe("name: mine\n");
	});

	test("writes only the enabled agents", async () => {
		const root = await mkdtemp(join(tmpdir(), "gw-sync-"));
		const only = resolveConfig({ agents: { enabled: ["codex"] } }, root, "x");
		expect(sync(only).written).not.toContain(".claude/settings.json");
	});
});

describe("nested agent docs", () => {
	async function monorepo(nested = true) {
		const repo = await tempRepo();
		await mkdir(join(repo.root, "apps/web"), { recursive: true });
		await mkdir(join(repo.root, "apps/api"), { recursive: true });
		await mkdir(join(repo.root, "dist"), { recursive: true });
		await writeFile(join(repo.root, ".gitignore"), "dist/\n");
		await writeFile(join(repo.root, "AGENTS.md"), "# Root\n");
		await writeFile(join(repo.root, "CLAUDE.md"), "Read AGENTS.md.\n");
		await writeFile(join(repo.root, "apps/web/AGENTS.md"), "# Web\n");
		await writeFile(join(repo.root, "apps/api/AGENTS.md"), "# API\n");
		await writeFile(join(repo.root, "apps/api/CLAUDE.md"), "# Mine\n");
		await writeFile(join(repo.root, "dist/AGENTS.md"), "# Built\n");
		const make = (on: boolean) =>
			resolveConfig(
				{ agents: { enabled: [], nested_docs: on } },
				repo.root,
				join(repo.root, "cagr.toml"),
			);
		return { root: repo.root, config: make(nested), make };
	}

	test("writes a shim beside each AGENTS.md that has no CLAUDE.md", async () => {
		const { root, config: on } = await monorepo();
		expect(sync(on, { check: true }).drifted).toContain("apps/web/CLAUDE.md");
		const result = sync(on);
		expect(result.written.filter((f) => f.endsWith("CLAUDE.md"))).toEqual([
			"apps/web/CLAUDE.md",
		]);
		const shim = await readFile(join(root, "apps/web/CLAUDE.md"), "utf8");
		expect(shim).toContain("Generated by `cagr sync`");
		expect(shim.trimEnd().endsWith("@AGENTS.md")).toBe(true);
		expect(await readFile(join(root, "apps/api/CLAUDE.md"), "utf8")).toBe(
			"# Mine\n",
		);
		expect(await readFile(join(root, "CLAUDE.md"), "utf8")).toBe(
			"Read AGENTS.md.\n",
		);
		expect(sync(on, { check: true }).drifted).toEqual([]);
		expect(result.kept).toEqual([]);
	});

	test("removes a shim whose AGENTS.md is gone, or when turned off", async () => {
		const { root, config: on, make } = await monorepo();
		sync(on);
		await rm(join(root, "apps/web/AGENTS.md"));
		expect(sync(on, { check: true }).drifted).toEqual(["apps/web/CLAUDE.md"]);
		expect(sync(on).removed).toEqual([
			{
				file: "apps/web/CLAUDE.md",
				why: "the AGENTS.md it imported is gone.",
			},
		]);
		await writeFile(join(root, "apps/web/AGENTS.md"), "# Web\n");
		sync(on);
		expect(sync(make(false)).removed.map((r) => r.file)).toEqual([
			"apps/web/CLAUDE.md",
		]);
		expect(await stat(join(root, "apps/api/CLAUDE.md")).then(() => true)).toBe(
			true,
		);
	});

	test("an edited shim or a symlink is the user's", async () => {
		const { root, config: on, make } = await monorepo();
		sync(on);
		const shim = join(root, "apps/web/CLAUDE.md");
		const edited = `${await readFile(shim, "utf8")}- Run tests with bun test\n`;
		await writeFile(shim, edited);
		expect(sync(on, { check: true }).drifted).toEqual([]);
		expect(sync(make(false)).removed).toEqual([]);
		expect(await readFile(shim, "utf8")).toBe(edited);
		await rm(shim);
		await symlink(join(root, "nowhere.md"), shim);
		expect(sync(on).written).not.toContain("apps/web/CLAUDE.md");
		expect(await stat(join(root, "nowhere.md")).catch(() => null)).toBeNull();
	});

	test("a git failure is reported when on and ignored when off", async () => {
		const root = await mkdtemp(join(tmpdir(), "gw-nogit-"));
		const at = (on: boolean) =>
			resolveConfig(
				{ agents: { enabled: [], nested_docs: on } },
				root,
				join(root, "cagr.toml"),
			);
		expect(() => sync(at(true), { check: true })).toThrow(
			"[agents] nested_docs needs git",
		);
		expect(sync(at(false), { check: true }).drifted).toEqual([
			".githooks/commit-msg",
			".githooks/pre-push",
		]);
	});

	test("is off by default", async () => {
		const { root } = await monorepo();
		const off = resolveConfig(
			{ agents: { enabled: [] } },
			root,
			join(root, "cagr.toml"),
		);
		expect(off.agents.nested_docs).toBe(false);
		expect(sync(off).written).not.toContain("apps/web/CLAUDE.md");
	});
});
