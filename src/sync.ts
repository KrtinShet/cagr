type HookEntry = { type: "command"; command: string; timeout: number };
type Group = { matcher?: string; hooks: HookEntry[] };
type HooksFile = { hooks?: Record<string, Group[]> } & Record<string, unknown>;

const timeoutSeconds: Record<AgentEvent, number> = {
	"session.start": 10,
	"command.before": 10,
	"file.before_edit": 10,
	"file.after_edit": 60,
	"turn.end": 300,
};

// How each agent's native events and tool names map onto cagr's events.
const wiring: Record<
	AgentName,
	{
		file: string;
		root: string;
		groups: [string, string | undefined, AgentEvent][];
	}
> = {
	claude: {
		file: ".claude/settings.json",
		root: '"$CLAUDE_PROJECT_DIR"',
		groups: [
			["SessionStart", undefined, "session.start"],
			["PreToolUse", "Bash", "command.before"],
			["PreToolUse", "Edit|Write|MultiEdit|NotebookEdit", "file.before_edit"],
			["PostToolUse", "Edit|Write|MultiEdit|NotebookEdit", "file.after_edit"],
			["Stop", undefined, "turn.end"],
		],
	},
	codex: {
		file: ".codex/hooks.json",
		root: '"$(git rev-parse --show-toplevel)"',
		groups: [
			["SessionStart", undefined, "session.start"],
			["PreToolUse", "^Bash$", "command.before"],
			["PreToolUse", "^(apply_patch|Edit|Write)$", "file.before_edit"],
			["PostToolUse", "^(apply_patch|Edit|Write)$", "file.after_edit"],
			["Stop", undefined, "turn.end"],
		],
	},
};

const ownCommand =
	/ hook (session\.start|command\.before|file\.before_edit|file\.after_edit|turn\.end) --agent (claude|codex)$/;

export function hookCommand(
	config: Config,
	agent: AgentName,
	event: AgentEvent,
) {
	return `${config.agents.command.replaceAll("{root}", wiring[agent].root)} hook ${event} --agent ${agent}`;
}

/** The agent's hooks file with cagr's entries replaced and everything else kept. */
export function mergeHooks(
	current: HooksFile,
	config: Config,
	agent: AgentName,
): HooksFile {
	const hooks: Record<string, Group[]> = {};
	for (const [event, groups] of Object.entries(current.hooks ?? {})) {
		const kept = groups
			.map((group) => ({
				...group,
				hooks: group.hooks.filter(
					(hook) => !ownCommand.test(hook.command ?? ""),
				),
			}))
			.filter((group) => group.hooks.length > 0);
		if (kept.length > 0) hooks[event] = kept;
	}
	for (const [native, matcher, event] of wiring[agent].groups) {
		const group: Group = {
			...(matcher ? { matcher } : {}),
			hooks: [
				{
					type: "command",
					command: hookCommand(config, agent, event),
					timeout: timeoutSeconds[event],
				},
			],
		};
		hooks[native] = [...(hooks[native] ?? []), group];
	}
	return { ...current, hooks };
}

export const generatedHeader =
	"# Generated by `cagr sync`. Edit cagr.toml and run `cagr sync` instead.";

export function gitHookScript(config: Config, hook: GitHookName) {
	const command = config.agents.command.replaceAll("{root}", wiring.codex.root);
	const program = command.split(" ")[0] ?? "";
	// A teammate without cagr installed can still commit; the agent hooks still guard agents.
	const missing = /^[\w.-]+$/.test(program)
		? `if ! command -v ${program} >/dev/null 2>&1; then\n\techo "cagr: ${program} is not installed, so the ${hook} hook did not run." >&2\n\texit 0\nfi\n`
		: "";
	return `#!/bin/sh\n${generatedHeader}\n${missing}exec ${command} git ${hook} "$@"\n`;
}

type Target = {
	path: string;
	desired: (current: string | null) => string;
	executable: boolean;
	/** A file teams often write by hand: sync leaves it alone unless it wrote it. */
	userOwned?: boolean;
	/** Another file GitHub reads in place of this one, if the repo has it. */
	shadowedBy?: () => string | null;
};

const generatedMark = "Generated by `cagr sync`";

/** The CLAUDE.md sync writes beside an AGENTS.md, so Claude Code reads the same instructions. */
export const claudeShim = `<!-- ${generatedMark}: Claude Code reads CLAUDE.md, so this imports AGENTS.md. Edit AGENTS.md instead. -->\n@AGENTS.md\n`;

/** Only a file that is exactly the shim: once someone adds to it, it is theirs. */
const isShim = (path: string) =>
	readFileSync(path, "utf8").replaceAll("\r\n", "\n") === claudeShim;

export class SyncError extends Error {}

/**
 * Repo-relative paths of files git tracks or would track (not ignored), named
 * `name`. Throws a SyncError when git cannot list them.
 */
function filesNamed(root: string, name: string): string[] {
	let listed: ReturnType<typeof Bun.spawnSync>;
	try {
		listed = Bun.spawnSync(
			["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
			{ cwd: root, stdout: "pipe", stderr: "pipe" },
		);
	} catch (error) {
		throw new SyncError(
			`[agents] nested_docs needs git to find AGENTS.md files, and git could not run: ${(error as Error).message}. Install git, or turn nested_docs off.`,
		);
	}
	if (listed.exitCode !== 0)
		throw new SyncError(
			`[agents] nested_docs needs git to find AGENTS.md files, and \`git ls-files\` failed: ${listed.stderr?.toString().trim()}. Fix that, or turn nested_docs off.`,
		);
	const paths = (listed.stdout?.toString() ?? "")
		.split("\0")
		.filter((path) => basename(path) === name && existsSync(join(root, path)));
	return [...new Set(paths)].sort();
}

const isSymlink = (path: string) => {
	try {
		return lstatSync(path).isSymbolicLink();
	} catch {
		return false;
	}
};

/** CLAUDE.md shims to write: beside each AGENTS.md with no CLAUDE.md, or with an unchanged shim. */
function shimTargets(config: Config): Target[] {
	if (!config.agents.nested_docs) return [];
	return filesNamed(config.root, "AGENTS.md")
		.map((agents) => join(config.root, dirname(agents), "CLAUDE.md"))
		.filter(
			// A symlink, even a dangling one, is the user's: writing through it could land outside the repo.
			(path) => !isSymlink(path) && (!existsSync(path) || isShim(path)),
		)
		.map((path) => ({
			path,
			executable: false,
			userOwned: true,
			desired: () => claudeShim,
		}));
}

/** Shims sync wrote that it would no longer write, with why each goes. */
function staleFiles(
	config: Config,
	wanted: Target[],
): { path: string; why: string }[] {
	let files: string[];
	try {
		files = filesNamed(config.root, "CLAUDE.md");
	} catch (error) {
		// With nested_docs off there is usually nothing to clean up, so a repo without git still syncs.
		if (!config.agents.nested_docs && error instanceof SyncError) return [];
		throw error;
	}
	const keep = new Set(wanted.map((target) => target.path));
	return files
		.map((file) => join(config.root, file))
		.filter((path) => !keep.has(path) && !isSymlink(path) && isShim(path))
		.map((path) => ({
			path,
			why: config.agents.nested_docs
				? "the AGENTS.md it imported is gone."
				: "[agents] nested_docs is off.",
		}));
}

function targets(config: Config, only?: "git"): Target[] {
	const agents = only === "git" ? [] : config.agents.enabled;
	const list: Target[] = agents.map((agent) => ({
		path: join(config.root, wiring[agent].file),
		executable: false,
		desired: (current) => {
			let parsed: HooksFile = {};
			if (current !== null && current.trim() !== "") {
				try {
					parsed = JSON.parse(current);
				} catch {
					throw new Error(
						`${wiring[agent].file} is not valid JSON. Fix it, then run \`cagr sync\` again.`,
					);
				}
			}
			return `${JSON.stringify(mergeHooks(parsed, config, agent), null, indentOf(current))}\n`;
		},
	}));
	for (const hook of gitHookNames)
		list.push({
			path: join(config.root, config.git.hooks_path, hook),
			executable: true,
			desired: () => gitHookScript(config, hook),
		});
	if (only !== "git") list.push(...shimTargets(config));
	if (only !== "git" && config.ci.github) {
		list.push({
			path: join(config.root, ".github", "workflows", "cagr.yml"),
			executable: false,
			desired: () => workflowYaml(config),
		});
		if (config.review.pr_sections.length > 0)
			list.push({
				path: join(config.root, ".github", "pull_request_template.md"),
				executable: false,
				userOwned: true,
				shadowedBy: () => otherTemplate(config.root),
				desired: () => pullRequestTemplate(config),
			});
		const owners = codeowners(config);
		if (owners)
			list.push({
				path: join(config.root, ".github", "CODEOWNERS"),
				executable: false,
				userOwned: true,
				shadowedBy: () =>
					["CODEOWNERS", "docs/CODEOWNERS"].find((path) =>
						existsSync(join(config.root, path)),
					) ?? null,
				desired: () => owners,
			});
	}
	return list;
}

/**
 * A pull request template GitHub reads other than the one sync writes: at the
 * root, in docs/ or .github/, in any case, or a PULL_REQUEST_TEMPLATE folder.
 */
function otherTemplate(root: string): string | null {
	for (const dir of ["", "docs", ".github"]) {
		let names: string[];
		try {
			names = readdirSync(join(root, dir));
		} catch {
			continue;
		}
		for (const name of names.sort()) {
			const path = dir ? `${dir}/${name}` : name;
			if (path === ".github/pull_request_template.md") continue;
			if (/^pull_request_template(\.md)?$/i.test(name)) return path;
		}
	}
	return null;
}

/** Whether the file exists under this exact name. On a case-insensitive disk, existsSync also matches the user's PULL_REQUEST_TEMPLATE.md. */
function hasExactName(path: string) {
	try {
		return readdirSync(dirname(path)).includes(basename(path));
	} catch {
		return false;
	}
}

/** The indent a JSON file already uses, so a rewrite does not fight the repo's formatter. */
export function indentOf(text: string | null): string | number {
	const indent = text?.match(/^[{[][^\n]*\n([ \t]+)\S/)?.[1];
	if (!indent) return 2;
	return indent.startsWith("\t") ? "\t" : indent.length;
}

export type SyncResult = {
	written: string[];
	unchanged: string[];
	drifted: string[];
	/** Hand-written files sync would have replaced, left as they are. */
	kept: string[];
	/** Generated files deleted, with why: the user keeps their own elsewhere, or sync no longer writes them. */
	removed: { file: string; why: string }[];
};

/** Writes the adapter files, or with `check` only reports which would change. */
export function sync(
	config: Config,
	options: { check?: boolean; only?: "git" } = {},
): SyncResult {
	const result: SyncResult = {
		written: [],
		unchanged: [],
		drifted: [],
		kept: [],
		removed: [],
	};
	const wanted = targets(config, options.only);
	if (options.only !== "git")
		for (const stale of staleFiles(config, wanted)) {
			const rel = toPosix(relative(config.root, stale.path));
			if (options.check) result.drifted.push(rel);
			else {
				rmSync(stale.path);
				result.removed.push({ file: rel, why: stale.why });
			}
		}
	for (const target of wanted) {
		const rel = toPosix(relative(config.root, target.path));
		const current = existsSync(target.path)
			? readFileSync(target.path, "utf8")
			: null;
		const shadow = target.shadowedBy?.();
		if (shadow) {
			result.kept.push(shadow);
			// GitHub reads the .github copy first, so a generated one left behind would hide the user's.
			if (current?.includes(generatedMark) && hasExactName(target.path)) {
				if (options.check) result.drifted.push(rel);
				else {
					rmSync(target.path);
					result.removed.push({
						file: rel,
						why: `GitHub reads it before ${shadow}, so yours would not apply.`,
					});
				}
			}
			continue;
		}
		if (
			target.userOwned &&
			current !== null &&
			!current.includes(generatedMark)
		) {
			result.kept.push(rel);
			continue;
		}
		const desired = target.desired(current);
		if (same(current, desired, target.path.endsWith(".json"))) {
			result.unchanged.push(rel);
			continue;
		}
		if (options.check) {
			result.drifted.push(rel);
			continue;
		}
		mkdirSync(dirname(target.path), { recursive: true });
		writeFileSync(target.path, desired);
		if (target.executable) chmodSync(target.path, 0o755);
		result.written.push(rel);
	}
	return result;
}

// JSON files are compared as data so a formatter's whitespace is not drift.
function same(current: string | null, desired: string, json: boolean) {
	if (current === null) return false;
	if (!json) return current === desired;
	try {
		return Bun.deepEquals(JSON.parse(current), JSON.parse(desired), true);
	} catch {
		return false;
	}
}

/** What to tell a person about each hand-written file sync left alone. */
export function keptNotes(kept: string[], removed: SyncResult["removed"] = []) {
	return [
		...kept.map(
			(file) =>
				`Left ${file} as it is: cagr did not write it. ${file.endsWith("CODEOWNERS") ? "Move its owners into [[risk.paths]] owners and delete it" : "Add the [review] pr_sections headings to it yourself, or delete it"} to let \`cagr sync\` manage it.`,
		),
		...removed.map(
			({ file, why }) =>
				`Deleted ${file}, which \`cagr sync\` wrote: ${why} Commit the deletion.`,
		),
	];
}

export class GitSetupError extends Error {}

export const notGitRepo =
	"This folder is not a git repo, so git never runs the commit-msg and pre-push hooks. Run `git init`, then `cagr install-git-hooks`.";

export async function isGitRepo(root: string) {
	return (await run(["git", "rev-parse", "--git-dir"], root)).ok;
}

/** Writes the git hook scripts and points core.hooksPath at them. */
export async function installGitHooks(config: Config) {
	const result = sync(config, { only: "git" });
	if (!(await isGitRepo(config.root))) throw new GitSetupError(notGitRepo);
	const set = await run(
		["git", "config", "core.hooksPath", config.git.hooks_path],
		config.root,
	);
	if (!set.ok)
		throw new GitSetupError(
			`Could not set core.hooksPath: ${set.output.trim()}`,
		);
	return result;
}
