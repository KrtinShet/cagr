import { describe, expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { resolveConfig } from "./config/load";
import { gitHookScript, hookCommand, indentOf, mergeHooks, sync } from "./sync";
import { config } from "./test/config";

const own = (event: string, agent = "claude") =>
	`cagr hook ${event} --agent ${agent}`;

describe("mergeHooks", () => {
	test("keeps the user's hooks, replaces cagr's, and is stable", () => {
		const user = { type: "command" as const, command: "echo mine", timeout: 5 };
		const current = {
			permissions: { allow: ["Bash(ls)"] },
			hooks: {
				PreToolUse: [
					{
						matcher: "Bash",
						hooks: [
							user,
							{
								type: "command" as const,
								command: "old/cagr hook command.before --agent claude",
								timeout: 1,
							},
						],
					},
				],
				Stop: [
					{
						hooks: [
							{
								type: "command" as const,
								command: own("turn.end"),
								timeout: 1,
							},
						],
					},
				],
			},
		};
		const merged = mergeHooks(current, config(), "claude");
		expect(merged.permissions).toEqual({ allow: ["Bash(ls)"] });
		expect(merged.hooks?.PreToolUse).toEqual([
			{ matcher: "Bash", hooks: [user] },
			{
				matcher: "Bash",
				hooks: [
					{ type: "command", command: own("command.before"), timeout: 10 },
				],
			},
			{
				matcher: "Edit|Write|MultiEdit|NotebookEdit",
				hooks: [
					{ type: "command", command: own("file.before_edit"), timeout: 10 },
				],
			},
		]);
		expect(merged.hooks?.Stop).toEqual([
			{ hooks: [{ type: "command", command: own("turn.end"), timeout: 300 }] },
		]);
		expect(mergeHooks(merged, config(), "claude")).toEqual(merged);
	});

	test("Codex gets regex matchers that include apply_patch", () => {
		const merged = mergeHooks({}, config(), "codex");
		expect(merged.hooks?.PostToolUse?.[0]?.matcher).toBe(
			"^(apply_patch|Edit|Write)$",
		);
		expect(merged.hooks?.SessionStart?.[0]).toEqual({
			hooks: [
				{
					type: "command",
					command: own("session.start", "codex"),
					timeout: 10,
				},
			],
		});
	});
});

test("{root} in the command becomes each agent's repo root", () => {
	const repo = config({ agents: { command: "{root}/bin/cagr" } });
	expect(hookCommand(repo, "claude", "turn.end")).toBe(
		'"$CLAUDE_PROJECT_DIR"/bin/cagr hook turn.end --agent claude',
	);
	expect(hookCommand(repo, "codex", "turn.end")).toBe(
		'"$(git rev-parse --show-toplevel)"/bin/cagr hook turn.end --agent codex',
	);
});

test("git hook scripts are marked generated and skip when cagr is missing", () => {
	const script = gitHookScript(config(), "pre-push");
	expect(script.split("\n").slice(0, 2)).toEqual([
		"#!/bin/sh",
		expect.stringContaining("Generated by `cagr sync`"),
	]);
	expect(script).toContain("command -v cagr");
	expect(script).toEndWith('exec cagr git pre-push "$@"\n');
	expect(
		gitHookScript(config({ agents: { command: "{root}/gw" } }), "commit-msg"),
	).not.toContain("command -v");
});

describe("sync", () => {
	async function repo() {
		const root = await mkdtemp(join(tmpdir(), "gw-sync-"));
		return resolveConfig({}, root, join(root, "cagr.toml"));
	}

	test("writes every file, then --check passes, then reports drift", async () => {
		const repoConfig = await repo();
		expect(sync(repoConfig).written).toEqual([
			".claude/settings.json",
			".codex/hooks.json",
			".githooks/commit-msg",
			".githooks/pre-push",
		]);
		expect(
			(await stat(join(repoConfig.root, ".githooks/pre-push"))).mode & 0o111,
		).toBeTruthy();
		expect(sync(repoConfig, { check: true }).drifted).toEqual([]);
		await writeFile(
			join(repoConfig.root, ".githooks/commit-msg"),
			"#!/bin/sh\n",
		);
		expect(sync(repoConfig, { check: true }).drifted).toEqual([
			".githooks/commit-msg",
		]);
	});

	test("JSON formatting alone is not drift", async () => {
		const repoConfig = await repo();
		sync(repoConfig);
		const file = join(repoConfig.root, ".claude/settings.json");
		await writeFile(
			file,
			JSON.stringify(JSON.parse(await readFile(file, "utf8"))),
		);
		expect(sync(repoConfig, { check: true }).drifted).toEqual([]);
	});

	test("a rewrite keeps the file's indent", async () => {
		const repoConfig = await repo();
		await mkdir(join(repoConfig.root, ".claude"));
		const file = join(repoConfig.root, ".claude/settings.json");
		await writeFile(file, '{\n\t"permissions": {}\n}\n');
		sync(repoConfig);
		expect(await readFile(file, "utf8")).toStartWith(
			'{\n\t"permissions": {},\n\t"hooks": {\n\t\t',
		);
		expect(indentOf('{\n    "a": 1\n}')).toBe(4);
		expect(indentOf(null)).toBe(2);
	});

	test("refuses to overwrite invalid JSON", async () => {
		const repoConfig = await repo();
		await mkdir(join(repoConfig.root, ".claude"));
		await writeFile(join(repoConfig.root, ".claude/settings.json"), "{ nope");
		expect(() => sync(repoConfig)).toThrow(
			".claude/settings.json is not valid JSON",
		);
	});

	test("writes only the enabled agents", async () => {
		const root = await mkdtemp(join(tmpdir(), "gw-sync-"));
		const only = resolveConfig({ agents: { enabled: ["codex"] } }, root, "x");
		expect(sync(only).written).not.toContain(".claude/settings.json");
	});
});
