type HookEntry = { type: "command"; command: string; timeout: number };
type Group = { matcher?: string; hooks: HookEntry[] };
type HooksFile = { hooks?: Record<string, Group[]> } & Record<string, unknown>;

const timeoutSeconds: Record<AgentEvent, number> = {
	"session.start": 10,
	"command.before": 10,
	"file.before_edit": 10,
	"file.after_edit": 60,
	"turn.end": 300,
};

// How each agent's native events and tool names map onto guardwright's events.
const wiring: Record<
	AgentName,
	{
		file: string;
		root: string;
		groups: [string, string | undefined, AgentEvent][];
	}
> = {
	claude: {
		file: ".claude/settings.json",
		root: '"$CLAUDE_PROJECT_DIR"',
		groups: [
			["SessionStart", undefined, "session.start"],
			["PreToolUse", "Bash", "command.before"],
			["PreToolUse", "Edit|Write|MultiEdit|NotebookEdit", "file.before_edit"],
			["PostToolUse", "Edit|Write|MultiEdit|NotebookEdit", "file.after_edit"],
			["Stop", undefined, "turn.end"],
		],
	},
	codex: {
		file: ".codex/hooks.json",
		root: '"$(git rev-parse --show-toplevel)"',
		groups: [
			["SessionStart", undefined, "session.start"],
			["PreToolUse", "^Bash$", "command.before"],
			["PreToolUse", "^(apply_patch|Edit|Write)$", "file.before_edit"],
			["PostToolUse", "^(apply_patch|Edit|Write)$", "file.after_edit"],
			["Stop", undefined, "turn.end"],
		],
	},
};

const ownCommand =
	/ hook (session\.start|command\.before|file\.before_edit|file\.after_edit|turn\.end) --agent (claude|codex)$/;

export function hookCommand(
	config: Config,
	agent: AgentName,
	event: AgentEvent,
) {
	return `${config.agents.command.replaceAll("{root}", wiring[agent].root)} hook ${event} --agent ${agent}`;
}

/** The agent's hooks file with guardwright's entries replaced and everything else kept. */
export function mergeHooks(
	current: HooksFile,
	config: Config,
	agent: AgentName,
): HooksFile {
	const hooks: Record<string, Group[]> = {};
	for (const [event, groups] of Object.entries(current.hooks ?? {})) {
		const kept = groups
			.map((group) => ({
				...group,
				hooks: group.hooks.filter(
					(hook) => !ownCommand.test(hook.command ?? ""),
				),
			}))
			.filter((group) => group.hooks.length > 0);
		if (kept.length > 0) hooks[event] = kept;
	}
	for (const [native, matcher, event] of wiring[agent].groups) {
		const group: Group = {
			...(matcher ? { matcher } : {}),
			hooks: [
				{
					type: "command",
					command: hookCommand(config, agent, event),
					timeout: timeoutSeconds[event],
				},
			],
		};
		hooks[native] = [...(hooks[native] ?? []), group];
	}
	return { ...current, hooks };
}

export const generatedHeader =
	"# Generated by `guardwright sync`. Edit guardwright.toml and run `guardwright sync` instead.";

export function gitHookScript(config: Config, hook: GitHookName) {
	const command = config.agents.command.replaceAll("{root}", wiring.codex.root);
	const program = command.split(" ")[0] ?? "";
	// A teammate without guardwright installed can still commit; the agent hooks still guard agents.
	const missing = /^[\w.-]+$/.test(program)
		? `if ! command -v ${program} >/dev/null 2>&1; then\n\techo "guardwright: ${program} is not installed, so the ${hook} hook did not run." >&2\n\texit 0\nfi\n`
		: "";
	return `#!/bin/sh\n${generatedHeader}\n${missing}exec ${command} git ${hook} "$@"\n`;
}

type Target = {
	path: string;
	desired: (current: string | null) => string;
	executable: boolean;
};

function targets(config: Config, only?: "git"): Target[] {
	const agents = only === "git" ? [] : config.agents.enabled;
	const list: Target[] = agents.map((agent) => ({
		path: join(config.root, wiring[agent].file),
		executable: false,
		desired: (current) => {
			let parsed: HooksFile = {};
			if (current !== null && current.trim() !== "") {
				try {
					parsed = JSON.parse(current);
				} catch {
					throw new Error(
						`${wiring[agent].file} is not valid JSON. Fix it, then run \`guardwright sync\` again.`,
					);
				}
			}
			return `${JSON.stringify(mergeHooks(parsed, config, agent), null, indentOf(current))}\n`;
		},
	}));
	for (const hook of gitHookNames)
		list.push({
			path: join(config.root, config.git.hooks_path, hook),
			executable: true,
			desired: () => gitHookScript(config, hook),
		});
	if (only !== "git" && config.ci.github) {
		list.push({
			path: join(config.root, ".github", "workflows", "guardwright.yml"),
			executable: false,
			desired: () => workflowYaml(config),
		});
		if (config.review.pr_sections.length > 0)
			list.push({
				path: join(config.root, ".github", "pull_request_template.md"),
				executable: false,
				desired: () => pullRequestTemplate(config),
			});
		const owners = codeowners(config);
		if (owners)
			list.push({
				path: join(config.root, ".github", "CODEOWNERS"),
				executable: false,
				desired: () => owners,
			});
	}
	return list;
}

/** The indent a JSON file already uses, so a rewrite does not fight the repo's formatter. */
export function indentOf(text: string | null): string | number {
	const indent = text?.match(/^[{[][^\n]*\n([ \t]+)\S/)?.[1];
	if (!indent) return 2;
	return indent.startsWith("\t") ? "\t" : indent.length;
}

export type SyncResult = {
	written: string[];
	unchanged: string[];
	drifted: string[];
};

/** Writes the adapter files, or with `check` only reports which would change. */
export function sync(
	config: Config,
	options: { check?: boolean; only?: "git" } = {},
): SyncResult {
	const result: SyncResult = { written: [], unchanged: [], drifted: [] };
	for (const target of targets(config, options.only)) {
		const rel = toPosix(relative(config.root, target.path));
		const current = existsSync(target.path)
			? readFileSync(target.path, "utf8")
			: null;
		const desired = target.desired(current);
		if (same(current, desired, target.path.endsWith(".json"))) {
			result.unchanged.push(rel);
			continue;
		}
		if (options.check) {
			result.drifted.push(rel);
			continue;
		}
		mkdirSync(dirname(target.path), { recursive: true });
		writeFileSync(target.path, desired);
		if (target.executable) chmodSync(target.path, 0o755);
		result.written.push(rel);
	}
	return result;
}

// JSON files are compared as data so a formatter's whitespace is not drift.
function same(current: string | null, desired: string, json: boolean) {
	if (current === null) return false;
	if (!json) return current === desired;
	try {
		return Bun.deepEquals(JSON.parse(current), JSON.parse(desired), true);
	} catch {
		return false;
	}
}

export class GitSetupError extends Error {}

export const notGitRepo =
	"This folder is not a git repo, so git never runs the commit-msg and pre-push hooks. Run `git init`, then `guardwright install-git-hooks`.";

export async function isGitRepo(root: string) {
	return (await run(["git", "rev-parse", "--git-dir"], root)).ok;
}

/** Writes the git hook scripts and points core.hooksPath at them. */
export async function installGitHooks(config: Config) {
	const result = sync(config, { only: "git" });
	if (!(await isGitRepo(config.root))) throw new GitSetupError(notGitRepo);
	const set = await run(
		["git", "config", "core.hooksPath", config.git.hooks_path],
		config.root,
	);
	if (!set.ok)
		throw new GitSetupError(
			`Could not set core.hooksPath: ${set.output.trim()}`,
		);
	return result;
}
